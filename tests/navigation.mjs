import assert from "node:assert/strict";
import { originalStream, rememberStream } from "../src/lib/navigation.mjs";
const a = { name: "Game A", url: "https://provider.test/a.ts" };
const b = { name: "Game B", url: "https://provider.test/b.ts" };
let history = rememberStream({ active: null, previous: null }, a);
assert.equal(history.previous, null);
history = rememberStream(history, b);
assert.equal(history.previous.url, a.url);
history = rememberStream(history, history.previous);
assert.equal(history.active.url, a.url);
assert.equal(history.previous.url, b.url);
history = rememberStream(history, history.previous);
assert.equal(history.active.url, b.url);
assert.equal(history.previous.url, a.url);
const same = rememberStream(history, { ...b, sourceUrl: b.url, url: "http://127.0.0.1:39221/mp4/fresh" });
assert.equal(same, history, "Replaying the same provider link must not overwrite the previous stream");
const proxiedA = { ...a, sourceUrl: a.url, url: "http://127.0.0.1:39221/mp4/another", history: {}, proxied: true };
assert.deepEqual(originalStream(proxiedA), a);
history = rememberStream(history, proxiedA);
assert.equal(history.active.url, a.url);
assert.equal(history.previous.url, b.url);
assert.notEqual(history.active.url, history.previous.url);
console.log("Last checks passed: repeated toggling, original links, duplicate playback, fresh proxy addresses.");
