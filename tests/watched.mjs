import assert from "node:assert/strict";
import { channelKey } from "../src/lib/library.mjs";
import { recordWatch, setWatchStatus, watchStatesFromHistory, validWatchStates } from "../src/lib/watched.mjs";
const channel = { name: "Show S01E01", url: "https://example.test/1.mp4" };
const key = channelKey(channel);
let states = {};
assert.equal(recordWatch(states, channel, { position: 0, duration: 100 }), states);
assert.equal(recordWatch(states, channel, { position: 20, duration: Infinity }), states);
states = recordWatch(states, channel, { position: 10, duration: 100 }, 1);
assert.equal(states[key].status, "started");
states = recordWatch(states, channel, { position: 99, duration: 100 }, 2);
assert.equal(states[key].status, "watched");
assert.equal(recordWatch(states, channel, { position: 10, duration: 100 }), states, "Rewatching must keep the watched check");
states = setWatchStatus(states, channel, false, 3);
assert.equal(states[key].status, "unwatched");
states = setWatchStatus(states, channel, true, 4);
assert.equal(JSON.parse(JSON.stringify(states))[key].status, "watched");
for (let i = 0; i < 300; i++) states = recordWatch(states, { name: String(i), url: String(i) }, { position: 100, duration: 100, ended: true });
assert.equal(states[key].status, "watched", "Watched markers must outlive the 200-item resume history");
assert.ok(validWatchStates(states));
assert.ok(!validWatchStates({ broken: { status: "unknown", updatedAt: 1 } }));
const migrated = watchStatesFromHistory({ a: { key: "a", position: 99, ended: true, updatedAt: 1 }, b: { key: "b", position: 10, ended: false, updatedAt: 2 }, c: { key: "c", position: 0, ended: false, updatedAt: 3 } });
assert.equal(migrated.a.status, "watched");
assert.equal(migrated.b.status, "started");
assert.equal(migrated.c, undefined);
console.log("Watched checks passed: actual progress, completion, manual marks, persistence, legacy migration, retention.");
