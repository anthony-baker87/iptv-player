import assert from "node:assert/strict";
import { channelKey, episodeInfo, resumable, updateHistory, historyItems, formatTime } from "../src/lib/library.mjs";
assert.deepEqual(episodeInfo("Example Show S02E03 - Title"), { series: "Example Show", season: 2, episode: 3 });
assert.deepEqual(episodeInfo("Example Show 1x04"), { series: "Example Show", season: 1, episode: 4 });
assert.equal(episodeInfo("Live Sports"), null);
assert.equal(resumable(100, Infinity), false);
assert.equal(resumable(1, 300), false);
assert.equal(resumable(100, 300), true);
assert.equal(resumable(299, 300), false);
assert.equal(resumable(100, 300, true), false);
const first = { name: "Show S01E01", url: "https://example.test/1.mp4", group: "Series" };
const second = { ...first, name: "Show S01E02", url: "https://example.test/2.mp4" };
let history = updateHistory({}, first, { position: 80, duration: 100, ended: false }, 1);
history = updateHistory(history, second, { position: 10, duration: 100, ended: false }, 2);
const reset = updateHistory(history, first, { position: 0, duration: 100, ended: false, reset: true }, 0);
assert.equal(reset[channelKey(first)].position, 0);
assert.equal(resumable(reset[channelKey(first)].position, 100), false);
assert.equal(historyItems(history, [first, second])[0].name, second.name);
assert.equal(historyItems(history, [first, second]).length, 1);
assert.equal(historyItems(history, []).length, 0);
assert.equal(updateHistory(history, first, { position: 50, duration: Infinity }), history);
assert.equal(channelKey({ ...first, rawAttrs: { "tvg-id": "123" } }), channelKey({ ...first, url: "changed", rawAttrs: { "tvg-id": "123" } }));
assert.equal(formatTime(3661), "1:01:01");
assert.equal(formatTime(80), "1:20");
for (let i = 0; i < 210; i++) history = updateHistory(history, { name: String(i), url: String(i) }, { position: 10, duration: 100 }, i + 3);
assert.equal(Object.keys(history).length, 200);
console.log("Library checks passed: stable keys, resume eligibility, episode grouping, history limit.");
