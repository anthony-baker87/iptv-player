import assert from "node:assert/strict";
import { seasonInfo, episodeInfo } from "../src/lib/library.mjs";
import { organizeSearch, browseRows } from "../src/lib/browse.mjs";
const names = ["Breaking Bad S02E10", "Breaking Bad S01E02", "Breaking Bad S10E01", "Breaking Bad S01E01", "Breaking Bad S02E02", "Breaking Bad S03", "Breaking Bad Movie", "Unrelated"];
const channels = names.map((name, index) => ({ name, url: `https://example.test/${index}` }));
const result = organizeSearch(channels, "breaking bad");
assert.equal(result.count, 7);
const seasons = result.items.filter((item) => item.type === "season");
assert.deepEqual(seasons.map((group) => group.season), [1, 2, 3, 10]);
assert.deepEqual(seasons[0].channels.map((channel) => channel.name), ["Breaking Bad S01E01", "Breaking Bad S01E02"]);
assert.deepEqual(seasons[1].channels.map((channel) => channel.name), ["Breaking Bad S02E02", "Breaking Bad S02E10"]);
assert.equal(seasons[0].label, "Season 1");
assert.equal(browseRows(result, new Set()).length, 5);
assert.equal(browseRows(result, new Set([seasons[0].key])).length, 7);
assert.deepEqual(channels.map((channel) => channel.name), names, "Search must not mutate the playlist");
const plain = ["BBC world", "BBC 10", "BBC Asia", "BBC 2"].map((name) => ({ name }));
assert.deepEqual(organizeSearch(plain, "bbc").items.map((item) => item.channel.name), ["BBC 2", "BBC 10", "BBC Asia", "BBC world"]);
assert.equal(organizeSearch(channels, "missing").count, 0);
assert.equal(organizeSearch(channels, "").items[0].channel, channels[0]);
assert.deepEqual(seasonInfo("Breaking.Bad_Season 2 Episode 3"), { series: "Breaking Bad", season: 2, episode: 3 });
assert.deepEqual(episodeInfo("Breaking Bad S01.E02"), { series: "Breaking Bad", season: 1, episode: 2 });
assert.equal(episodeInfo("Breaking Bad S01"), null);
assert.equal(seasonInfo("S01E01"), null);
const multiple = organizeSearch([{ name: "Breaking Bad S01E01" }, { name: "Breaking Bad Extras S01E01" }], "breaking bad");
assert.ok(multiple.items.every((group) => group.label.includes(group.series)));
console.log("Browse checks passed: season detection, numeric ordering, collapse/expand rows, alphabetical fallback, non-mutating search.");
